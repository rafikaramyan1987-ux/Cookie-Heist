/**
 * Solver report for every level: npx tsx scripts/playtest/solve.ts [--md docs/solver.md]
 * (the same solver as tests/unit/solver.test.ts: a winning run, replayed from its recorded inputs).
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { ALL_LEVELS, getLevel } from '../../src/levels/all';
import { solveLevel } from '../../src/game/solve';
import { difficulty } from '../../src/game/difficulty';
const EN = JSON.parse(readFileSync('src/locales/en.json', 'utf8')) as Record<string, string>;
const t = (k: string) => EN[k] ?? k;

const md = process.argv.includes('--md') ? process.argv[process.argv.indexOf('--md') + 1] : '';
let out = '# Solver report\n\nGenerated by `npx tsx scripts/playtest/solve.ts --md docs/solver.md` (the same check as `tests/unit/solver.test.ts`). For every level the solver looks for a winning run on the real game logic — the playtest bot (good, average, beginner; 8 seeds each), then the hint planner — and proves a bot solution by replaying its recorded inputs frame by frame on a fresh world.\n\n';
out += '| # | Level | Name | Solved | Found by | Replay | Winning run | Par | Route | Difficulty |\n|---|---|---|---|---|---|---|---|---|---|\n';
let n = 0,
  bad = 0;
for (const [h, i] of ALL_LEVELS) {
  const L = getLevel(h, i);
  const s = solveLevel(L);
  const d = difficulty(L);
  n++;
  if (!s.solved) bad++;
  const line = `| ${n} | ${L.id}${L.finale ? ' (finale)' : ''} | ${t(L.nameKey)} | ${s.solved ? 'yes' : '**NO**'} | ${s.by || '—'} | ${s.frames ? (s.replayed ? `won again (${s.frames} frames)` : '**failed**') : 'follower won'} | ${s.time} s | ${L.par} s | ${d.route} | ${d.score} |`;
  out += line + '\n';
  console.log(line);
}
out += `\n**${n - bad} / ${n} levels solved.**\n`;
console.log(`${n - bad} / ${n} solved`);
if (md) writeFileSync(md, out);
if (bad) process.exit(1);
