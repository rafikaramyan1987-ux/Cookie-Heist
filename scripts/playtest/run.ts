/**
 * Headless playtest: plays every level on the real game logic with beginner / average / good bots.
 * usage: npx tsx scripts/playtest/run.ts [--runs N] [--house H] [--level L] [--md docs/playtest.md]
 */
import { writeFileSync } from 'node:fs';
import { getLevel, levelId, LEVEL_SRC } from '../../src/levels/index';
import { World } from '../../src/game/world';
import { simulate, PROFILES } from '../../src/game/bot';

const args = process.argv.slice(2);
const arg = (k: string, d: string) => {
  const i = args.indexOf(k);
  return i >= 0 ? args[i + 1] : d;
};
const RUNS = +arg('--runs', '24');
const onlyHouse = arg('--house', '');
const onlyLevel = arg('--level', '');
const md = arg('--md', '');

export interface Row {
  id: string;
  house: number;
  index: number;
  finale: boolean;
  solvable: boolean;
  prof: Record<string, { win: number; time: number; spotted: number; noise: number; caught: number; timeout: number }>;
}

const rows: Row[] = [];
for (let h = 0; h < LEVEL_SRC.length; h++) {
  if (onlyHouse !== '' && +onlyHouse !== h) continue;
  for (let i = 0; i < LEVEL_SRC[h].length; i++) {
    if (onlyLevel !== '' && +onlyLevel !== i) continue;
    const L = getLevel(h, i);
    const row: Row = { id: levelId(h, i), house: h, index: i, finale: L.finale, solvable: false, prof: {} };
    for (const p of ['beginner', 'average', 'good'] as const) {
      let win = 0,
        time = 0,
        spotted = 0,
        noise = 0,
        caught = 0,
        timeout = 0;
      for (let s = 0; s < RUNS; s++) {
        const w = new World(L, { seed: 1000 * h + 37 * i + s + 1, jitter: 1.2 });
        const r = simulate(w, PROFILES[p], s + 1);
        if (r.won) {
          win++;
          time += r.time;
        } else if (r.status === 'play') timeout++;
        else caught++;
        spotted += r.spotted;
        noise += r.noises;
      }
      row.prof[p] = { win: win / RUNS, time: win ? time / win : 0, spotted: spotted / RUNS, noise: noise / RUNS, caught, timeout };
      if (win > 0) row.solvable = true;
    }
    rows.push(row);
    const f = (p: string) => {
      const r = row.prof[p];
      return `${p[0]}:${(r.win * 100).toFixed(0).padStart(3)}% ${r.time.toFixed(0).padStart(3)}s sp${r.spotted.toFixed(1)} c${r.caught} t${r.timeout}`;
    };
    console.log(`${row.id.padEnd(13)} ${row.solvable ? 'OK ' : 'NO!'} ${f('beginner')} | ${f('average')} | ${f('good')}`);
  }
}

if (md) {
  const names = ['City Apartment', 'Family House', "Grandma's Cottage", 'Snowy Chalet', 'Grand Mansion'];
  let out = `# Playtest report\n\nGenerated by \`npm run playtest\` — ${RUNS} runs per level and profile on the real game logic (guard simulation + bot pathfinding).\n\n`;
  out += `Targets: house 1 nights 1–3 beginner ≥ 90%; normal nights average ≈ 70%; finales ≈ 50%; nothing below 35% (average profile).\n\n`;
  out += `| Level | Solvable | Beginner win | Average win | Good win | Avg time (avg) | Spotted / run (avg) | Noise events / run (avg) |\n|---|---|---|---|---|---|---|---|\n`;
  for (const r of rows) {
    const a = r.prof.average;
    out += `| ${names[r.house]} ${r.index + 1}${r.finale ? ' (finale)' : ''} | ${r.solvable ? 'yes' : '**no**'} | ${(r.prof.beginner.win * 100).toFixed(0)}% | ${(a.win * 100).toFixed(0)}% | ${(r.prof.good.win * 100).toFixed(0)}% | ${a.time.toFixed(1)} s | ${a.spotted.toFixed(2)} | ${a.noise.toFixed(1)} |\n`;
  }
  writeFileSync(md, out);
  console.log('wrote', md);
}
